-- Q1. Tela "Meu bairro": alertas ATIVOS com nome do bairro, mais graves primeiro
SELECT a.id, b.nome AS bairro, a.severidade, a.mensagem, a.criado_em
  FROM TB_ALERTA a
  JOIN TB_BAIRRO b ON b.id = a.id_bairro
 WHERE a.status = 'ATIVO'
 ORDER BY CASE a.severidade WHEN 'CRITICO' THEN 1 ELSE 2 END, a.criado_em DESC;

-- Q2. Painel da Defesa Civil: media e maxima de chuva nas ultimas 24h por bairro
SELECT b.nome AS bairro,
       ROUND(AVG(l.valor), 2) AS media_mm_h,
       MAX(l.valor)           AS maxima_mm_h,
       COUNT(*)               AS qtd_leituras
  FROM TB_LEITURA l
  JOIN TB_SENSOR s ON s.id = l.id_sensor
  JOIN TB_BAIRRO b ON b.id = s.id_bairro
 WHERE s.tipo = 'PLUVIOMETRO'
   AND l.data_hora >= SYSTIMESTAMP - INTERVAL '24' HOUR
 GROUP BY b.nome
 ORDER BY maxima_mm_h DESC;

-- Q3. Ranking de bairros com mais alertas nos ultimos 30 dias
SELECT b.nome AS bairro,
       COUNT(a.id) AS total_alertas,
       SUM(CASE WHEN a.severidade = 'CRITICO' THEN 1 ELSE 0 END) AS criticos
  FROM TB_BAIRRO b
  LEFT JOIN TB_ALERTA a ON a.id_bairro = b.id
                       AND a.criado_em >= SYSTIMESTAMP - INTERVAL '30' DAY
 GROUP BY b.nome
 ORDER BY total_alertas DESC;

-- Q4. Ocupacao dos abrigos por bairro (em %)
SELECT b.nome AS bairro,
       SUM(ab.capacidade)                  AS capacidade_total,
       SUM(ab.vagas_ocupadas)              AS ocupadas,
       SUM(ab.capacidade - ab.vagas_ocupadas) AS vagas_livres,
       ROUND(SUM(ab.vagas_ocupadas) * 100 / SUM(ab.capacidade), 1) AS ocupacao_pct
  FROM TB_ABRIGO ab
  JOIN TB_BAIRRO b ON b.id = ab.id_bairro
 GROUP BY b.nome
 ORDER BY ocupacao_pct DESC;

-- Q5. Ultima leitura de cada sensor, com situacao calculada
SELECT s.codigo, s.tipo, b.nome AS bairro, l.valor, l.data_hora,
       CASE WHEN l.valor >= s.limite_critico THEN 'CRITICO'
            WHEN l.valor >= s.limite_alerta  THEN 'ATENCAO'
            ELSE 'NORMAL' END AS situacao
  FROM TB_SENSOR s
  JOIN TB_BAIRRO b  ON b.id = s.id_bairro
  JOIN TB_LEITURA l ON l.id_sensor = s.id
 WHERE l.data_hora = (SELECT MAX(l2.data_hora) FROM TB_LEITURA l2 WHERE l2.id_sensor = s.id)
 ORDER BY b.nome, s.codigo;

-- Q6. Relatos dos cidadaos por bairro e status
SELECT b.nome AS bairro, r.status, COUNT(*) AS quantidade
  FROM TB_RELATO r
  JOIN TB_BAIRRO b ON b.id = r.id_bairro
 GROUP BY b.nome, r.status
 ORDER BY b.nome, r.status;

-- Q7. Abrigos com vaga nos bairros que estao com alerta CRITICO ativo
SELECT b.nome AS bairro, ab.nome AS abrigo, ab.endereco,
       ab.capacidade - ab.vagas_ocupadas AS vagas_livres
  FROM TB_ABRIGO ab
  JOIN TB_BAIRRO b ON b.id = ab.id_bairro
 WHERE ab.vagas_ocupadas < ab.capacidade
   AND EXISTS (SELECT 1 FROM TB_ALERTA a
                WHERE a.id_bairro = b.id AND a.status = 'ATIVO' AND a.severidade = 'CRITICO')
 ORDER BY vagas_livres DESC;
