BEGIN
  FOR t IN (SELECT column_value AS nome FROM TABLE(sys.odcivarchar2list(
      'TB_RELATO', 'TB_ALERTA', 'TB_LEITURA', 'TB_ABRIGO',
      'TB_SENSOR', 'TB_USUARIO', 'TB_BAIRRO'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.nome || ' CASCADE CONSTRAINTS';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
