CREATE TABLE TB_BAIRRO (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nome         VARCHAR2(100 CHAR) NOT NULL,
  cidade       VARCHAR2(100 CHAR) NOT NULL,
  nivel_risco  VARCHAR2(10)       NOT NULL,
  CONSTRAINT pk_bairro PRIMARY KEY (id),
  CONSTRAINT uk_bairro_nome_cidade UNIQUE (nome, cidade),
  CONSTRAINT ck_bairro_risco CHECK (nivel_risco IN ('BAIXO', 'MEDIO', 'ALTO'))
);

CREATE TABLE TB_USUARIO (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nome        VARCHAR2(100 CHAR) NOT NULL,
  email       VARCHAR2(150 CHAR) NOT NULL,
  senha_hash  VARCHAR2(100 CHAR) NOT NULL,
  perfil      VARCHAR2(10)       NOT NULL,
  telefone    VARCHAR2(20  CHAR),
  id_bairro   NUMBER        NOT NULL,
  criado_em   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_usuario PRIMARY KEY (id),
  CONSTRAINT uk_usuario_email UNIQUE (email),
  CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'CIDADAO')),
  CONSTRAINT fk_usuario_bairro FOREIGN KEY (id_bairro) REFERENCES TB_BAIRRO (id)
);

CREATE TABLE TB_SENSOR (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo          VARCHAR2(30 CHAR)  NOT NULL,
  tipo            VARCHAR2(15)       NOT NULL,
  id_bairro       NUMBER        NOT NULL,
  limite_alerta   NUMBER(8,2)   NOT NULL,
  limite_critico  NUMBER(8,2)   NOT NULL,
  ativo           NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_sensor PRIMARY KEY (id),
  CONSTRAINT uk_sensor_codigo UNIQUE (codigo),
  CONSTRAINT ck_sensor_tipo CHECK (tipo IN ('NIVEL_RIO', 'PLUVIOMETRO')),
  CONSTRAINT ck_sensor_limites CHECK (limite_critico > limite_alerta),
  CONSTRAINT ck_sensor_ativo CHECK (ativo IN (0, 1)),
  CONSTRAINT fk_sensor_bairro FOREIGN KEY (id_bairro) REFERENCES TB_BAIRRO (id)
);

CREATE TABLE TB_LEITURA (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_sensor  NUMBER       NOT NULL,
  valor      NUMBER(8,2)  NOT NULL,
  data_hora  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_leitura PRIMARY KEY (id),
  CONSTRAINT ck_leitura_valor CHECK (valor >= 0),
  CONSTRAINT fk_leitura_sensor FOREIGN KEY (id_sensor) REFERENCES TB_SENSOR (id)
);

CREATE TABLE TB_ALERTA (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_bairro   NUMBER         NOT NULL,
  id_leitura  NUMBER,
  severidade  VARCHAR2(10)        NOT NULL,
  mensagem    VARCHAR2(300 CHAR)  NOT NULL,
  status      VARCHAR2(10)        DEFAULT 'ATIVO' NOT NULL,
  criado_em   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_alerta PRIMARY KEY (id),
  CONSTRAINT uk_alerta_leitura UNIQUE (id_leitura), -- 1 leitura gera no maximo 1 alerta
  CONSTRAINT ck_alerta_sev CHECK (severidade IN ('ATENCAO', 'CRITICO')),
  CONSTRAINT ck_alerta_status CHECK (status IN ('ATIVO', 'ENCERRADO')),
  CONSTRAINT fk_alerta_bairro FOREIGN KEY (id_bairro) REFERENCES TB_BAIRRO (id),
  CONSTRAINT fk_alerta_leitura FOREIGN KEY (id_leitura) REFERENCES TB_LEITURA (id)
);

CREATE TABLE TB_ABRIGO (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nome            VARCHAR2(100 CHAR) NOT NULL,
  endereco        VARCHAR2(200 CHAR) NOT NULL,
  capacidade      NUMBER(5)     NOT NULL,
  vagas_ocupadas  NUMBER(5)     DEFAULT 0 NOT NULL,
  id_bairro       NUMBER        NOT NULL,
  CONSTRAINT pk_abrigo PRIMARY KEY (id),
  CONSTRAINT ck_abrigo_capacidade CHECK (capacidade > 0),
  CONSTRAINT ck_abrigo_vagas CHECK (vagas_ocupadas >= 0 AND vagas_ocupadas <= capacidade),
  CONSTRAINT fk_abrigo_bairro FOREIGN KEY (id_bairro) REFERENCES TB_BAIRRO (id)
);

CREATE TABLE TB_RELATO (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_usuario  NUMBER         NOT NULL,
  id_bairro   NUMBER         NOT NULL,
  descricao   VARCHAR2(1000 CHAR) NOT NULL,
  status      VARCHAR2(12)   DEFAULT 'ABERTO' NOT NULL,
  criado_em   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_relato PRIMARY KEY (id),
  CONSTRAINT ck_relato_status CHECK (status IN ('ABERTO', 'VERIFICADO', 'DESCARTADO')),
  CONSTRAINT fk_relato_usuario FOREIGN KEY (id_usuario) REFERENCES TB_USUARIO (id),
  CONSTRAINT fk_relato_bairro FOREIGN KEY (id_bairro) REFERENCES TB_BAIRRO (id)
);

-- Indices para as consultas mais frequentes
CREATE INDEX ix_leitura_sensor_data ON TB_LEITURA (id_sensor, data_hora);
CREATE INDEX ix_alerta_bairro_status ON TB_ALERTA (id_bairro, status);

-- Rede de seguranca contra alertas duplicados: apenas 1 alerta ATIVO por (bairro, severidade)
CREATE UNIQUE INDEX ux_alerta_ativo ON TB_ALERTA (
  CASE WHEN status = 'ATIVO' THEN id_bairro END,
  CASE WHEN status = 'ATIVO' THEN severidade END
);

